#!/usr/bin/env node
/**
 * Re-generates src/perchance/art-styles.js from the LIVE Perchance "🎨 Art Style" dropdown.
 *
 *   npm run sync:types
 *
 * Run it whenever Perchance adds/renames styles. Labels are copied verbatim.
 */
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import { applyClientHints } from '../src/browser/fingerprint.js';
import { openBrowserSession } from '../src/browser/launch.js';
import { config } from '../src/config.js';
import { openGenerator, readLiveOptions } from '../src/perchance/generator.js';

const target = fileURLToPath(new URL('../src/perchance/art-styles.js', import.meta.url));

const session = await openBrowserSession();
try {
  const page = session.context.pages()[0] ?? (await session.context.newPage());
  if (config.spoofClientHints) await applyClientHints(session.context, page);

  const frame = await openGenerator(page);
  const live = await readLiveOptions(frame);
  const styles = live.artStyle.map((o) => o.label).filter(Boolean);
  if (styles.length < 5) throw new Error(`Only ${styles.length} art styles found – refusing to overwrite.`);
  if (!live.numImages.some((o) => o.value.trim() === '4')) {
    console.warn(
      '⚠️  Perchance no longer offers "4" in "How many?" – the generator will fail with IMAGE_COUNT_UNAVAILABLE.',
    );
  }
  const defaultStyle = live.artStyle.find((o) => o.selected)?.label || styles[0];

  const source = `// AUTO-GENERATED by \`npm run sync:types\` (scripts/sync-art-styles.js) – do not edit by hand.
// Source: the live "🎨 Art Style" dropdown of ${config.perchanceUrl}
//
// Labels are copied VERBATIM (including Unicode-bold entries such as "𝗡𝗼 𝘀𝘁𝘆𝗹𝗲") because the API
// contract requires every "type" to be identical to Perchance's own dropdown values.

export const ART_STYLES_SYNCED_AT = ${JSON.stringify(new Date().toISOString())};

/** Perchance's pre-selected option. */
export const DEFAULT_ART_STYLE = ${JSON.stringify(defaultStyle)};

/** All ${styles.length} options, in Perchance's order. */
export const ART_STYLES = Object.freeze([
${styles.map((s) => `  ${JSON.stringify(s)},`).join('\n')}
]);
`;

  await writeFile(target, source, 'utf8');
  console.log(`✔ Wrote ${styles.length} art styles to ${target}`);
  console.log(`  default: ${defaultStyle}`);
  console.log(`  "How many?" options: ${live.numImages.map((o) => o.label).join(', ')}`);
  console.log(`  "Shape" options: ${live.shape.map((o) => `${o.label} (${o.value})`).join(', ')}`);
} finally {
  await session.close();
}
